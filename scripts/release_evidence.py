"""Release gate and evidence writer (run last; `scripts/make_release.sh` runs the whole sequence with fresh logs).

    python scripts/release_evidence.py <version>

Writes release/RELEASE.md (version, gate result, registration check, test and UAT status, headline numbers read
from the output files) and release/MANIFEST.sha256 (SHA-256 of every packaged file except the manifest itself).
Exits non-zero, and says why in RELEASE.md, unless ALL of these hold:
  - the stage-7 config matches its registered SHA-256;
  - pytest collected > 0 tests with no failures or errors (release/logs/pytest_junit.xml);
  - every automated UAT case is PASS (owner cases marked "n/a — owner review" are reported, not passed);
  - no RELEASE_BLOCKED.json / VERIFY_FAILED.json marker exists under outputs/ (history excluded);
  - the required logs exist in release/logs/.
It never signs owner cases. No project imports.
"""
import csv
import hashlib
import json
import pathlib
import sys
import xml.etree.ElementTree as ET

ROOT = pathlib.Path(__file__).resolve().parents[1]
LOGS = ("run_all.log", "pytest.log", "pytest_junit.xml", "ui_check.log", "build_uat.log")
EXCLUDE_DIRS = {"__pycache__", ".pytest_cache", ".venv", "history", "marts"}


def sha(p):
    return hashlib.sha256(p.read_bytes()).hexdigest()


def packaged_files(root):
    for p in sorted(root.rglob("*")):
        rel = p.relative_to(root)
        if not p.is_file() or set(rel.parts) & EXCLUDE_DIRS or rel.parts[0] == ".git":
            continue
        if rel.parts[:2] == ("data", "raw") and p.name != ".gitkeep":
            continue
        if any(part.endswith(".egg-info") for part in rel.parts) or rel == pathlib.Path("release/MANIFEST.sha256"):
            continue
        yield rel, p


def main(version, root=ROOT):
    REL = root / "release"
    REL.mkdir(exist_ok=True)
    cfg_sha = sha(root / "config" / "date_policy.yaml")
    registered = (root / "outputs" / "stage7" / "PREREGISTRATION_SHA256.txt").read_text().split()[0]
    junit = REL / "logs" / "pytest_junit.xml"
    j = ET.parse(junit).getroot() if junit.exists() else ET.fromstring("<testsuite tests='0'/>")
    suite = j if j.tag == "testsuite" else j.find("testsuite")
    tests = {k: int(suite.get(k, 0)) for k in ("tests", "failures", "errors", "skipped")}
    uat = list(csv.DictReader(open(root / "outputs" / "stage4" / "uat_results.csv")))
    pol = {(r["target"], r["policy"]): r for r in csv.DictReader(open(root / "outputs" / "stage7" / "policy_results.csv"))}
    mon = json.loads((root / "outputs" / "stage7" / "monitoring" / "monitoring.json").read_text())
    nom = mon["nominal_in_control_arl"]["B0_0.90"]
    gate = []
    if cfg_sha != registered:
        gate.append("stage-7 config does not match its registered SHA-256")
    if tests["tests"] == 0 or tests["failures"] or tests["errors"]:
        gate.append(f"pytest: {tests}")
    bad_uat = [r["id"] for r in uat if not r["automated result"].startswith("n/a") and r["automated result"] != "PASS"]
    if bad_uat:
        gate.append("automated UAT not PASS: " + ", ".join(bad_uat))
    markers = [str(p.relative_to(root)) for name in ("RELEASE_BLOCKED.json", "VERIFY_FAILED.json")
               for p in (root / "outputs").rglob(name) if "history" not in p.parts]
    if markers:
        gate.append("block markers present: " + ", ".join(markers))
    missing = [f for f in LOGS if not (REL / "logs" / f).exists()]
    if missing:
        gate.append("missing logs: " + ", ".join(missing))
    owner_open = [r["id"] for r in uat if r["automated result"].startswith("n/a")]
    pct = lambda r: f"{float(r['coverage']) * 100:.2f}%"
    days = lambda r: f"{float(r['mean_promised_days']):.3f}"
    L = [f"# Release {version}", "",
         "Generated by `scripts/release_evidence.py` from the files in this package. The ZIP's own SHA-256 is given "
         "with the delivery (a file cannot contain its own hash).", "",
         f"## Gate: {'PASS' if not gate else 'FAIL'}", "",
         *(["- automated checks above all hold"] if not gate else [f"- {g}" for g in gate]),
         f"- owner cases still open (never signed by this script): {', '.join(owner_open) or 'none'}", "",
         "## Registration", "",
         f"- `config/date_policy.yaml` SHA-256 `{cfg_sha}`",
         f"- registered SHA-256 `{registered}` → {'MATCH' if cfg_sha == registered else 'MISMATCH'}",
         "- The registered config is unchanged; deviations and implementation fixes are logged in "
         "`docs/DATE_POLICY_DECISIONS.md` (D1, I1–I5), not written back into the config.", "",
         "## Tests and acceptance", "",
         f"- pytest: {tests['tests']} collected, {tests['failures']} failures, {tests['errors']} errors, "
         f"{tests['skipped']} skipped (`release/logs/pytest.log`, `pytest_junit.xml`)",
         "- full pipeline from the raw CSVs: `release/logs/run_all.log`",
         *[f"- `release/logs/{f}` SHA-256 `{sha(REL / 'logs' / f)}`" for f in LOGS if (REL / "logs" / f).exists()],
         "- UAT (`outputs/stage4/UAT.md`): " + ", ".join(f"{r['id']} {r['automated result']}" for r in uat), "",
         "## Headline numbers (read from the output files)", "",
         "| Item | Value | File |", "|---|---|---|"]
    for t, p in [("0.90", "B0_state_quantile"), ("0.90", "Q2_qr_conformal_A"), ("0.90", "Olist_promise"),
                 ("olist_matched", "B0_state_quantile")]:
        r = pol[(t, p)]
        L.append(f"| {p} @ {t} | {pct(r)} covered, {days(r)} mean days | outputs/stage7/policy_results.csv |")
    L += [f"| single-week LLR rule, exact in-control ARL | {nom['single_week_llr']['arl_weeks']:.3f} weeks | outputs/stage7/monitoring/monitoring.json |",
          f"| threshold rule, exact in-control ARL | {nom['threshold']['arl_weeks']:.5g} weeks | outputs/stage7/monitoring/monitoring.json |", "",
          "## Manifest", "", "`release/MANIFEST.sha256`: one line per packaged file (`sha256  path`).", ""]
    (REL / "RELEASE.md").write_text("\n".join(L), encoding="utf-8")
    lines = [f"{sha(p)}  {rel.as_posix()}" for rel, p in packaged_files(root)]
    (REL / "MANIFEST.sha256").write_text("\n".join(lines) + "\n")
    print(f"{len(lines)} files in manifest; gate {'PASS' if not gate else 'FAIL: ' + '; '.join(gate)}")
    return 0 if not gate else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1]))
